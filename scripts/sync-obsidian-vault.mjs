#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const args = process.argv.slice(2);

const defaultVaultCandidates = [
  process.env.AD_PROJECT_OBSIDIAN_VAULT,
  "D:\\Obsidian (Installed)\\Vault Folder (Non Standard Folder)\\Ken's Vault",
].filter(Boolean);

const rootArtifactExtensions = new Set([".md", ".json", ".txt", ".csv"]);
const rootArtifactSkipNames = new Set([
  "package-lock.json",
  "package.json",
]);
const defaultRootArtifactMaxBytes = 1_500_000;

function argValue(flag) {
  const index = args.indexOf(flag);
  if (index === -1) {
    return null;
  }
  return args[index + 1] ?? null;
}

function hasFlag(flag) {
  return args.includes(flag);
}

function normalizeVaultLink(absPath, vaultRoot) {
  return path.relative(vaultRoot, absPath).replaceAll(path.sep, "/");
}

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function readText(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function writeText(filePath, content) {
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, content, "utf8");
}

function copyFile(source, target) {
  ensureDir(path.dirname(target));
  fs.copyFileSync(source, target);
}

function ensureVaultLinks(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const content = readText(filePath);
  if (content.includes("## Vault Links")) {
    return;
  }
  const firstLineEnd = content.indexOf("\n");
  if (firstLineEnd === -1) {
    return;
  }
  const links = [
    "",
    "## Vault Links",
    "",
    "- [[00 Home/Vault Map]]",
    "- [[05 Mirror/Anti Matrix Mirror/Index]]",
    "- [[05 Mirror/Anti Matrix Mirror/root-artifacts/Index]]",
    "",
  ].join("\n");
  writeText(filePath, `${content.slice(0, firstLineEnd)}\n${links}${content.slice(firstLineEnd + 1)}`);
}

function listFilesRecursive(dirPath) {
  const files = [];
  if (!fs.existsSync(dirPath)) return files;
  for (const entry of fs.readdirSync(dirPath, { withFileTypes: true })) {
    if (entry.name === ".git" || entry.name === "node_modules") {
      continue;
    }
    const abs = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      files.push(...listFilesRecursive(abs));
    } else if (entry.isFile()) {
      files.push(abs);
    }
  }
  return files.sort((a, b) => a.localeCompare(b));
}

function copyDirectory(sourceDir, targetDir) {
  for (const sourceFile of listFilesRecursive(sourceDir)) {
    const rel = path.relative(sourceDir, sourceFile);
    copyFile(sourceFile, path.join(targetDir, rel));
  }
}

function writeFolderIndex({ vaultRoot, folderPath, title, connectedHubs = [] }) {
  const entries = fs
    .readdirSync(folderPath, { withFileTypes: true })
    .filter((entry) => entry.name !== "Index.md")
    .sort((a, b) => a.name.localeCompare(b.name));

  const lines = [`# ${title}`, "", "This note is generated by `npm run obsidian:sync`.", ""];

  if (connectedHubs.length > 0) {
    lines.push("## Connected Hubs", "");
    for (const hub of connectedHubs) {
      lines.push(`- [[${hub}]]`);
    }
    lines.push("");
  }

  const dirs = entries.filter((entry) => entry.isDirectory());
  const files = entries.filter((entry) => entry.isFile());

  if (dirs.length > 0) {
    lines.push("## Folders", "");
    for (const dir of dirs) {
      const indexPath = path.join(folderPath, dir.name, "Index.md");
      const linkTarget = fs.existsSync(indexPath)
        ? normalizeVaultLink(indexPath, vaultRoot).replace(/\.md$/u, "")
        : normalizeVaultLink(path.join(folderPath, dir.name), vaultRoot);
      lines.push(`- [[${linkTarget}]]`);
    }
    lines.push("");
  }

  if (files.length > 0) {
    lines.push("## Files", "");
    for (const file of files) {
      const linkTarget = normalizeVaultLink(path.join(folderPath, file.name), vaultRoot).replace(/\.md$/u, "");
      lines.push(`- [[${linkTarget}]]`);
    }
    lines.push("");
  }

  writeText(path.join(folderPath, "Index.md"), `${lines.join("\n").trimEnd()}\n`);
}

function writeRecursiveIndexes(vaultRoot, folderPath, titlePrefix, connectedHubs = []) {
  if (!fs.existsSync(folderPath)) return;
  for (const entry of fs.readdirSync(folderPath, { withFileTypes: true })) {
    if (!entry.isDirectory()) {
      continue;
    }
    const child = path.join(folderPath, entry.name);
    writeRecursiveIndexes(vaultRoot, child, `${titlePrefix} / ${entry.name}`, connectedHubs);
  }
  writeFolderIndex({ vaultRoot, folderPath, title: titlePrefix, connectedHubs });
}

function resolveVaultPath() {
  const explicit = argValue("--vault");
  if (explicit) {
    return path.resolve(explicit);
  }
  for (const candidate of defaultVaultCandidates) {
    if (candidate && fs.existsSync(candidate)) {
      return candidate;
    }
  }
  throw new Error(
    "Obsidian vault not found. Set AD_PROJECT_OBSIDIAN_VAULT or pass --vault \"D:\\\\path\\\\to\\\\vault\".",
  );
}

function mirrorRootArtifacts(vaultRoot, includeLarge) {
  const targetDir = path.join(vaultRoot, "05 Mirror", "Anti Matrix Mirror", "root-artifacts");
  ensureDir(targetDir);
  const skipped = [];

  for (const entry of fs.readdirSync(repoRoot, { withFileTypes: true })) {
    if (!entry.isFile()) {
      continue;
    }
    const ext = path.extname(entry.name).toLowerCase();
    if (!rootArtifactExtensions.has(ext) || rootArtifactSkipNames.has(entry.name)) {
      continue;
    }
    const source = path.join(repoRoot, entry.name);
    const stats = fs.statSync(source);
    if (!includeLarge && stats.size > defaultRootArtifactMaxBytes) {
      skipped.push(`${entry.name} (${stats.size} bytes)`);
      continue;
    }
    copyFile(source, path.join(targetDir, entry.name));
  }

  writeFolderIndex({
    vaultRoot,
    folderPath: targetDir,
    title: "Anti Matrix Root Artifacts Index",
    connectedHubs: [
      "00 Home/Vault Map",
      "70 Logs/Historical Log Index",
    ],
  });

  return skipped;
}

function mirrorRepoDocs(vaultRoot) {
  const mirrorRoot = path.join(vaultRoot, "05 Mirror", "Anti Matrix Mirror");
  ensureDir(mirrorRoot);

  const localDocs = path.join(repoRoot, "docs");
  if (fs.existsSync(localDocs)) {
    copyDirectory(localDocs, path.join(mirrorRoot, "docs"));
  }

  for (const rootFile of ["README.md", "AI_AGENT_CONTEXT.md", "MISSION_CONTROL.md"]) {
    const source = path.join(repoRoot, rootFile);
    if (fs.existsSync(source)) {
      copyFile(source, path.join(mirrorRoot, rootFile));
    }
  }

  const skippedRootArtifacts = mirrorRootArtifacts(vaultRoot, hasFlag("--include-large-root-artifacts"));
  ensureVaultLinks(path.join(mirrorRoot, "AI_AGENT_CONTEXT.md"));
  ensureVaultLinks(path.join(mirrorRoot, "root-artifacts", "AI_AGENT_CONTEXT.md"));

  const docsDir = path.join(mirrorRoot, "docs");
  if (fs.existsSync(docsDir)) {
    writeRecursiveIndexes(vaultRoot, docsDir, "Anti Matrix Docs Index", [
      "00 Home/Vault Map",
    ]);
  }

  writeFolderIndex({
    vaultRoot,
    folderPath: mirrorRoot,
    title: "Anti Matrix Repo Mirror Index",
    connectedHubs: [
      "00 Home/Vault Map",
      "05 Mirror/Anti Matrix Mirror/root-artifacts/Index",
    ],
  });

  return skippedRootArtifacts;
}

function upsertLink(filePath, linkLine, marker = "## Connected Notes") {
  if (!fs.existsSync(filePath)) {
    return;
  }
  let content = readText(filePath);
  if (content.includes(linkLine)) {
    return;
  }
  if (!content.includes(marker)) {
    content = `${content.trimEnd()}\n\n${marker}\n\n${linkLine}\n`;
  } else {
    content = content.replace(marker, `${marker}\n\n${linkLine}`);
  }
  writeText(filePath, content);
}

function logProgress(vaultRoot, message) {
  const now = new Date();
  const dateStamp = now.toISOString().slice(0, 10);
  const timeStamp = now.toISOString();
  const liveDir = path.join(vaultRoot, "70 Logs", "Live Progress");
  const dailyPath = path.join(liveDir, `${dateStamp}.md`);

  if (!fs.existsSync(dailyPath)) {
    writeText(
      dailyPath,
      [
        `# Live Progress - ${dateStamp}`,
        "",
        "## Navigation",
        "",
        "- [[00 Home/Vault Map]]",
        "- [[70 Logs/Execution Timeline]]",
        "- [[70 Logs/Live Progress Index]]",
        "",
        "## Entries",
        "",
      ].join("\n"),
    );
  }

  fs.appendFileSync(dailyPath, `- ${timeStamp}: **[Anti Matrix]** ${message}\n`, "utf8");

  const dailyNotes = fs
    .readdirSync(liveDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md") && entry.name !== "Index.md")
    .map((entry) => entry.name)
    .sort()
    .reverse();

  const indexLines = [
    "# Live Progress Index",
    "",
    "Live project execution notes generated by `npm run obsidian:log`.",
    "",
    "## Navigation",
    "",
    "- [[00 Home/Vault Map]]",
    "- [[70 Logs/Execution Timeline]]",
    "- [[70 Logs/Historical Log Index]]",
    "",
    "## Daily Logs",
    "",
    ...dailyNotes.map((name) => `- [[70 Logs/Live Progress/${name.replace(/\.md$/u, "")}]]`),
    "",
  ];
  writeText(path.join(vaultRoot, "70 Logs", "Live Progress Index.md"), indexLines.join("\n"));

  upsertLink(path.join(vaultRoot, "70 Logs", "Execution Timeline.md"), "- [[70 Logs/Live Progress Index]]");
  upsertLink(path.join(vaultRoot, "00 Home", "Vault Map.md"), "- [[70 Logs/Live Progress Index]]", "## Fast Links");
}

